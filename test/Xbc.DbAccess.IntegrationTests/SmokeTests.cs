    /// <summary>
    /// 真库集成测试冒烟集：验证测试基础设施（建表/清理/方言工厂）与核心写读路径
    /// （插入自增回填、bulk 原生路径、Upsert 两条路径、条件更新删除）在 PostgreSQL 与 SQL Server 上的行为一致。
    /// </summary>
