        [SkippableFact]
        public async Task InsertAsync_BackfillsIdentity_AndFindsRow()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);
            var user = new SmokeUser
            {
                Name = "Alice",
                Age = 30,
                Balance = 100.5m,
                CreatedAt = new DateTime(2026, 1, 15, 10, 30, 0),
                IsActive = true
            };

            await entitySet.InsertAsync(user);
            Assert.True(user.Id > 0, "插入后应回填自增主键");

            var found = await entitySet.FindAsync(user.Id);
            Assert.NotNull(found);
            Assert.Equal("Alice", found!.Name);
            Assert.Equal(30, found.Age);
            Assert.Equal(100.5m, found.Balance);
            Assert.Equal(new DateTime(2026, 1, 15, 10, 30, 0), found.CreatedAt);
            Assert.True(found.IsActive);
        }

        [SkippableFact]
        public async Task InsertAsync_WithExplicitIdentity_UsesSpecifiedId()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);

            // 带显式自增主键插入：按显式值写入（值优先，不回填），Pg 的 GENERATED BY DEFAULT、
            // SqlServer 的 SET IDENTITY_INSERT 包裹均支持该语义
            var user = new SmokeUser { Id = 4343, Name = "ExplicitInsert", Age = 35, CreatedAt = new DateTime(2026, 8, 1), IsActive = true };
            await entitySet.InsertAsync(user);
            Assert.Equal(4343, user.Id);

            var found = await entitySet.FindAsync(4343);
            Assert.NotNull(found);
            Assert.Equal("ExplicitInsert", found!.Name);
            Assert.Equal(35, found.Age);
        }

        [SkippableFact]
        public async Task InsertRangeAsync_MixedExplicitAndDefaultIdentity_InsertsEachCorrectly()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);

            // 混合场景（部分带显式 ID、部分默认值）：同为逐条插入，显式值按值写入、默认值由数据库生成并回填
            var explicitUser = new SmokeUser { Id = 4444, Name = "MixedExplicit", Age = 40, CreatedAt = new DateTime(2026, 9, 1), IsActive = true };
            var defaultUser = new SmokeUser { Name = "MixedDefault", Age = 41, CreatedAt = new DateTime(2026, 9, 2), IsActive = false };
            var affectedRows = await entitySet.InsertRangeAsync(new[] { explicitUser, defaultUser });
            Assert.Equal(2, affectedRows);

            Assert.Equal(4444, explicitUser.Id);
            Assert.True(defaultUser.Id > 0, "默认值路径应回填自增主键");

            Assert.NotNull(await entitySet.FindAsync(4444));
            Assert.NotNull(await entitySet.FindAsync(defaultUser.Id));
        }

        [SkippableFact]
        public async Task BulkInsertAsync_WritesAllRows_WithNativePath()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);
            var users = Enumerable.Range(1, 50).Select(i => new SmokeUser
            {
                Name = $"User{i:000}",
                Age = 20 + (i % 40),
                Balance = i * 1.25m,
                CreatedAt = new DateTime(2026, 2, 1, 8, 0, 0).AddMinutes(i),
                IsActive = i % 2 == 0
            }).ToList();

            var affectedRows = await entitySet.BulkInsertAsync(users);
            Assert.Equal(50, affectedRows);

            // 原生路径（Pg COPY BINARY / SqlServer SqlBulkCopy）不回填自增 ID，但行数与列值必须完整落库
            Assert.Equal(50, await entitySet.AsQuery().CountAsync());
            Assert.Equal(25, await entitySet.Where(u => u.IsActive).CountAsync());

            var found = await DbAccess.FromSql<SmokeUser>($"SELECT * FROM {Qi("it_smoke_user")} WHERE {Qi("Name")} = 'User010'").FirstOrDefaultAsync();
            Assert.NotNull(found);
            Assert.Equal(30, found!.Age);
            Assert.Equal(12.5m, found.Balance);
        }

        [SkippableFact]
        public async Task UpsertAsync_InsertsThenUpdates()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);

            // 插入路径：自增主键为默认值，插入并回填 ID
            var user = new SmokeUser { Name = "Bob", Age = 25, Balance = 10m, CreatedAt = new DateTime(2026, 3, 1), IsActive = true };
            await entitySet.UpsertAsync(user);
            Assert.True(user.Id > 0, "Upsert 插入路径应回填自增主键");

            // 更新路径：带显式主键冲突，更新除主键外全部列
            user.Age = 26;
            user.Name = "BobUpdated";
            var affectedRows = await entitySet.UpsertAsync(user);
            // MySQL 的 ON DUPLICATE KEY UPDATE 更新路径按协议返回 2（插入 1/变更 2/未变更 0），其余方言返回 1
            Assert.Equal(Dialect == RealDbDialect.MySql ? 2 : 1, affectedRows);

            Assert.Equal(1, await entitySet.AsQuery().CountAsync());
            var found = await entitySet.FindAsync(user.Id);
            Assert.NotNull(found);
            Assert.Equal("BobUpdated", found!.Name);
            Assert.Equal(26, found.Age);
        }

        [SkippableFact]
        public async Task UpsertAsync_WithExplicitIdentity_UsesSpecifiedIdOnInsertPath()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);

            // 带显式自增主键 upsert 不存在的行：按显式值插入（Pg 的 GENERATED BY DEFAULT、
            // SqlServer 的 SET IDENTITY_INSERT 包裹均支持该语义）
            var user = new SmokeUser { Id = 4242, Name = "Explicit", Age = 40, CreatedAt = new DateTime(2026, 7, 1), IsActive = true };
            var affectedRows = await entitySet.UpsertAsync(user);
            Assert.Equal(1, affectedRows);

            var found = await entitySet.FindAsync(4242);
            Assert.NotNull(found);
            Assert.Equal("Explicit", found!.Name);

            // 再次 upsert 同一显式主键：命中已存在行，走更新路径
            user.Name = "ExplicitUpdated";
            await entitySet.UpsertAsync(user);
            Assert.Equal(1, await entitySet.AsQuery().CountAsync());
            Assert.Equal("ExplicitUpdated", (await entitySet.FindAsync(4242))!.Name);
        }

        [SkippableFact]
        public async Task UpsertAsync_NonPrimaryKeyIdentityDefaultValue_BackfillsConsistently()
        {
            SkipIfDialectUnavailable();
            Skip.If(Dialect == RealDbDialect.Sqlite, "SQLite 引擎不支持非主键自增列（AUTOINCREMENT 仅限 INTEGER PRIMARY KEY）");

            var entitySet = new EntitySet<SmokeSeqUser>(DbAccess);

            // 插入路径：非主键自增列由数据库生成并回填——支持取回子句的方言（Pg/SqlServer）单语句取回，
            // MySQL/Oracle 语句执行后按主键回读补齐（各方言取回行为一致）
            var inserted = new SmokeSeqUser { Code = "A1", Name = "First" };
            var affectedRows = await entitySet.UpsertAsync(inserted);
            Assert.Equal(1, affectedRows);
            Assert.True(inserted.Seq > 0, "非主键自增列在插入路径应回填");

            // 更新路径：冲突键命中已存在行，自增列保持既有值并回填到实体（回读按主键取既有值，取回子句返回目标行既有值）
            var updated = new SmokeSeqUser { Code = "A1", Name = "Second" };
            await entitySet.UpsertAsync(updated);
            Assert.Equal(inserted.Seq, updated.Seq);

            var found = await entitySet.FindAsync("A1");
            Assert.NotNull(found);
            Assert.Equal("Second", found!.Name);
        }

        [SkippableFact]
        public async Task ConditionalUpdateAndDelete_AffectMatchingRows()
        {
            SkipIfDialectUnavailable();
            var entitySet = new EntitySet<SmokeUser>(DbAccess);
            var users = Enumerable.Range(1, 10).Select(i => new SmokeUser
            {
                Name = $"Cond{i:00}",
                Age = 10 + i,
                CreatedAt = new DateTime(2026, 4, 1),
                IsActive = i % 3 == 0
            }).ToList();
            await entitySet.InsertRangeAsync(users);

            // 条件更新：Age > 15 的行 Age 统一为 99
            var updated = await entitySet.UpdateAsync(u => new { Age = 99 }, u => u.Age > 15);
            Assert.Equal(5, updated);

            // 条件删除：删除 Age = 99 的行
            var deleted = await entitySet.DeleteAsync(u => u.Age == 99);
            Assert.Equal(5, deleted);

            Assert.Equal(5, await entitySet.AsQuery().CountAsync());
            Assert.Equal(0, await entitySet.Where(u => u.Age == 99).CountAsync());
        }

