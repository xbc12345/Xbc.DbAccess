using System.Text;
using Xbc.DbAccess.Common;

namespace Xbc.DbAccess.Oracle
{
    /// <summary>
    /// Oracle 数据库 SQL 构建器。
    /// </summary>
    internal sealed class OracleSqlBuilder : SqlBuilderBase
    {
        /// <summary>
        /// Oracle 数据库 SQL 构建器实例。
        /// </summary>
        public static readonly OracleSqlBuilder Instance = new OracleSqlBuilder();

        /// <summary>
        /// 获取 SQL 方言。
        /// </summary>
        public override ISqlDialect SqlDialect => OracleDialect.Instance;

        private OracleSqlBuilder()
        {
        }

        /// <summary>
        /// 构建自增 ID 输出子句：RETURNING INTO，<c>RETURNING "Id" INTO :out_Id</c>，
        /// 自增 ID 由提供程序在执行后写回输出参数，不产生结果集（不能以 ExecuteScalar 读取）。
        /// </summary>
        /// <param name="identity">自增 ID 取回上下文。</param>
        /// <returns>RETURNING INTO 子句。</returns>
        /// <exception cref="ArgumentException">
        /// 未提供标识列名或输出参数名时抛出：RETURNING INTO 依赖二者生成合法子句，静默忽略会生成必然执行失败的 SQL。
        /// </exception>
        protected override string BuildInsertOutputClauseAfterValues(InsertIdentityContext identity)
        {
            if (string.IsNullOrEmpty(identity.IdentityColumn))
                throw new ArgumentException("启用自增 ID 输出时必须提供标识列名。", nameof(identity));

            if (string.IsNullOrEmpty(identity.OutputParameterName))
                throw new ArgumentException("Oracle 的 RETURNING INTO 子句需要自增 ID 输出参数名。", nameof(identity));

            return $"RETURNING {identity.IdentityColumn} INTO {identity.OutputParameterName}";
        }

        /// <summary>
        /// 构建 Upsert 语句：MERGE 主键匹配时更新，不匹配时插入（要求 Oracle 9i+）。
        /// <para>已知限制：MERGE 不支持 RETURNING INTO，自增 ID 无法随 Upsert 取回，identity 参数被忽略（由调用方按方言判定不取回）。</para>
        /// <para>Oracle 语法约束：表/源别名不能用 AS（直接跟别名）；USING 子查询需 FROM DUAL；ON 条件需加括号。</para>
        /// </summary>
        /// <param name="tableName">表名。</param>
        /// <param name="insertColumns">插入列名列表（已引用，含主键；自增列为默认值时排除、带显式值时包含）。</param>
        /// <param name="insertValues">插入值列表（参数占位符，与 insertColumns 平行）。</param>
        /// <param name="conflictKey">冲突键列名（已引用，主键列名）。</param>
        /// <param name="updateColumns">更新列名列表（已引用，由入口统一推导传入）。</param>
        /// <param name="identity">自增列参与方式上下文，本方言不生成取回子句（MERGE 无法配合 RETURNING INTO）；显式写入形态直接按列清单写入（GENERATED BY DEFAULT 语义的标识列允许显式值插入）。</param>
        /// <returns></returns>
        protected override string BuildUpsertSqlCore(string tableName, List<string> insertColumns, List<string> insertValues, string conflictKey, List<string> updateColumns, InsertIdentityContext identity = null)
        {
            // 更新赋值清单：目标列 = 源表列，string.Join 单行拼接（与 EntitySet 的 SET 风格一致）
            var updateAssignments = new List<string>(updateColumns.Count);
            foreach (var column in updateColumns)
            {
                updateAssignments.Add($"t.{column} = src.{column}");
            }

            // 源表列清单：插入列用对应参数占位符；冲突键被排除（自增主键）时以 NULL 填充，ON 永不匹配、恒走插入路径
            var sourceColumns = new List<string>(insertColumns.Count + 1);
            for (int i = 0; i < insertColumns.Count; i++)
            {
                sourceColumns.Add($"{insertValues[i]} AS {insertColumns[i]}");
            }

            if (!insertColumns.Contains(conflictKey))
                sourceColumns.Add($"NULL AS {conflictKey}");

            // INSERT 子句的值清单引用源表列
            var sourceValueColumns = new List<string>(insertColumns.Count);
            foreach (var column in insertColumns)
            {
                sourceValueColumns.Add($"src.{column}");
            }

            var sqlBuilder = new StringBuilder();
            sqlBuilder.AppendLine($"MERGE INTO {tableName} t");
            sqlBuilder.AppendLine($"USING (SELECT {string.Join(", ", sourceColumns)} FROM DUAL) src");
            sqlBuilder.AppendLine($"ON (t.{conflictKey} = src.{conflictKey})");
            sqlBuilder.AppendLine("WHEN MATCHED THEN");
            sqlBuilder.AppendLine($"    UPDATE SET {string.Join(", ", updateAssignments)}");

            sqlBuilder.AppendLine("WHEN NOT MATCHED THEN");
            // MERGE 的 INSERT 子句不带 INTO（区别于普通 INSERT INTO）
            sqlBuilder.AppendLine($"    INSERT ({string.Join(", ", insertColumns)})");
            sqlBuilder.AppendLine($"    VALUES ({string.Join(", ", sourceValueColumns)})");
            return sqlBuilder.ToString();
        }

        /// <summary>
        /// 构建窗口查询语句（分页与 Skip/Take 共享的核心）。对于 Oracle 12c 及以上版本，使用 OFFSET 和 FETCH NEXT；
        /// 更低版本（含版本未知）使用 ROWNUM 三层嵌套实现，offset 由入口换算后直传。
        /// <para>约定：querySql 不得自带顶层 ORDER BY，排序统一由 orderBy 参数传入。
        /// ROWNUM 取号前的排序必须唯一且位于最内层，querySql 自带顶层排序会与追加的排序
        /// 产生同层冲突（ORA-00933）；其余窗口实现中 querySql 的排序同样会被外层 orderBy 覆盖，
        /// 故此约定适用于全部窗口调用。</para>
        /// </summary>
        /// <param name="querySql">原始查询 SQL（已修剪），不得自带顶层 ORDER BY。</param>
        /// <param name="offset">跳过的行数。</param>
        /// <param name="fetch">取回的行数。</param>
        /// <param name="orderBy">ORDER BY 子句。</param>
        /// <param name="appendRowOrder">是否保证输出行序。</param>
        /// <param name="serverInfo">服务器信息。</param>
        /// <returns></returns>
        protected override string BuildWindowSqlCore(string querySql,
            int offset,
            int fetch,
            string orderBy,
            bool appendRowOrder,
            DbServerInfo serverInfo = null)
        {
            if (IsOffsetAndFetchSupported(serverInfo))
            {
                // 对于 Oracle 12c 及以上版本，使用 OFFSET 和 FETCH NEXT 实现分页
                // 注意：Oracle 的内联视图（派生表）别名不允许使用 AS 关键字，直接跟别名
                var subqueryAlias = SqlIdentifierHelper.Generate("q");
                var sqlBuilder = new StringBuilder();
                sqlBuilder.AppendLine($"SELECT * FROM (");
                sqlBuilder.AppendLine(SqlFormatter.IndentLines(querySql));
                sqlBuilder.AppendLine($") {subqueryAlias}");
                sqlBuilder.AppendLine($"ORDER BY {orderBy}");
                sqlBuilder.AppendLine($"OFFSET {offset} ROWS");
                sqlBuilder.AppendLine($"FETCH NEXT {fetch} ROWS ONLY");
                return sqlBuilder.ToString();
            }
            else
            {
                long endRow = offset + fetch;// 计算结束行号

                // 使用 ROWNUM 实现，兼容 Oracle 11g 及以下版本
                // querySql 由调用方保证不带顶层 ORDER BY（见方法说明），排序在此处唯一追加
                // 内层别名与行号别名带随机段防撞：实体列名恰为 t/rn（Oracle 未引用别名折叠为大写 T/RN，
                // 声明为精确 "T"/"RN" 时相撞）时固定别名会产生内联视图列名重复（ORA-00918）
                var innerAlias = SqlIdentifierHelper.Generate("t");
                var rowNumberAlias = SqlIdentifierHelper.Generate("rn");

                var sqlBuilder = new StringBuilder();
                sqlBuilder.AppendLine("SELECT * FROM (");
                sqlBuilder.AppendLine($"    SELECT {innerAlias}.*, ROWNUM AS {rowNumberAlias} FROM (");

                // 添加原始查询 + 排序
                sqlBuilder.AppendLine(SqlFormatter.IndentLines(querySql, 2));
                sqlBuilder.AppendLine($"        ORDER BY {orderBy}");
                sqlBuilder.AppendLine($"    ) {innerAlias}");
                sqlBuilder.AppendLine($"    WHERE ROWNUM <= {endRow}");
                sqlBuilder.AppendLine($") WHERE {rowNumberAlias} > {offset}");

                // 顶层排序契约：行序必须等于排序键序——最外层若不显式 ORDER BY，过滤后行集的行序在 SQL 语义上
                // 不保证（ROWNUM 的分配序无输出序契约），与 OFFSET/FETCH 路径（有顶层 ORDER BY）一致；
                // 包裹场景（appendRowOrder=false）行序由外层保证，嵌套派生表形态本身可再包裹，省略尾部排序
                if (appendRowOrder)
                    sqlBuilder.AppendLine($"ORDER BY {orderBy}");

                return sqlBuilder.ToString();
            }
        }

        /// <summary>
        /// 是否支持 OFFSET 和 FETCH 语句。
        /// </summary>
        /// <param name="serverInfo"></param>
        /// <returns></returns>
        private bool IsOffsetAndFetchSupported(DbServerInfo serverInfo)
        {
            // 如果没有版本信息，默认使用兼容语法
            if (serverInfo == null)
                return false;

            // 从 Oracle 12c 开始支持 OFFSET 和 FETCH NEXT（版本12.0）
            return serverInfo.MajorVersion >= 12;
        }
    }
}
