using System.Text;
using Xbc.DbAccess.Common;

namespace Xbc.DbAccess.SqlServer
{
    /// <summary>
    /// SQL Server 数据库 SQL 构建器。
    /// </summary>
    internal sealed class SqlServerSqlBuilder : SqlBuilderBase
    {
        /// <summary>
        /// SQL Server 数据库 SQL 构建器实例。
        /// </summary>
        public static readonly SqlServerSqlBuilder Instance = new SqlServerSqlBuilder();

        /// <summary>
        /// 获取 SQL 方言。
        /// </summary>
        public override ISqlDialect SqlDialect => SqlServerDialect.Instance;

        /// <summary>
        /// 
        /// </summary>
        private SqlServerSqlBuilder()
        {
        }

        /// <summary>
        /// 构建位于列清单与 VALUES 之间的自增 ID 输出子句：OUTPUT INSERTED，以结果集方式返回（由调用方以 ExecuteScalar 读取）。
        /// </summary>
        /// <param name="identity">自增 ID 取回上下文。</param>
        /// <returns>OUTPUT 子句。</returns>
        protected override string BuildInsertOutputClauseBeforeValues(InsertIdentityContext identity)
        {
            // 已知限制：目标表存在启用的触发器时，不带 INTO 的 OUTPUT 子句会被 SQL Server 拒绝执行，
            // 此类表需移除触发器或在实体映射上改用数据库端默认值方案
            return $"OUTPUT INSERTED.{identity.IdentityColumn}";
        }

        /// <summary>
        /// 构建插入语句：自增列带显式值（进入列清单）时，IDENTITY_INSERT 默认关闭的表无法显式插入标识列，
        /// 以同命令多语句批处理包裹 SET IDENTITY_INSERT ON/OFF（与 Upsert 的包裹一致）。
        /// </summary>
        /// <param name="tableName">表名。</param>
        /// <param name="columns">列名列表。</param>
        /// <param name="values">值列表。</param>
        /// <param name="identity">自增列参与方式上下文，null 表示无自增列参与。</param>
        /// <returns></returns>
        public override string BuildInsertSql(string tableName, List<string> columns, List<string> values, InsertIdentityContext identity = null)
        {
            var sql = base.BuildInsertSql(tableName, columns, values, identity);

            // 显式写入形态（契约：标识列已在列清单中）以 SET IDENTITY_INSERT 包裹
            if (identity != null && identity.IsExplicit)
            {
                var sqlBuilder = new StringBuilder();
                sqlBuilder.AppendLine($"SET IDENTITY_INSERT {tableName} ON;");
                sqlBuilder.Append(sql); // 基类语句自带行尾换行，追加的 ; 独占一行（与 Upsert 的批处理风格一致）
                sqlBuilder.AppendLine(";");
                sqlBuilder.AppendLine($"SET IDENTITY_INSERT {tableName} OFF;");
                return sqlBuilder.ToString();
            }

            return sql;
        }

        /// <summary>
        /// 构建 Upsert 语句：MERGE 主键匹配时更新，不匹配时插入（要求 SQL Server 2008+）。
        /// <para>已知限制：目标表存在启用的触发器时，OUTPUT 子句会被 SQL Server 拒绝执行（与 INSERT 的 OUTPUT 一致）。</para>
        /// </summary>
        /// <param name="tableName">表名。</param>
        /// <param name="insertColumns">插入列名列表（已引用，含主键；自增列为默认值时排除、带显式值时包含）。</param>
        /// <param name="insertValues">插入值列表（参数占位符，与 insertColumns 平行）。</param>
        /// <param name="conflictKey">冲突键列名（已引用，主键列名）。</param>
        /// <param name="updateColumns">更新列名列表（已引用，由入口统一推导传入）。</param>
        /// <param name="identity">自增列参与方式上下文，null 表示无自增列参与。</param>
        /// <returns></returns>
        protected override string BuildUpsertSqlCore(string tableName, List<string> insertColumns, List<string> insertValues, string conflictKey, List<string> updateColumns, InsertIdentityContext identity = null)
        {
            // 更新赋值清单：目标列 = 源表列，string.Join 单行拼接（与 EntitySet 的 SET 风格一致）
            var updateAssignments = new List<string>(updateColumns.Count);
            foreach (var column in updateColumns)
            {
                updateAssignments.Add($"t.{column} = src.{column}");
            }

            // 源表列清单：插入列用对应参数占位符；冲突键被排除（自增主键）时以 NULL 填充，ON 永不匹配、恒走插入路径
            var sourceColumns = new List<string>(insertColumns.Count + 1);
            for (int i = 0; i < insertColumns.Count; i++)
            {
                sourceColumns.Add($"{insertValues[i]} AS {insertColumns[i]}");
            }

            if (!insertColumns.Contains(conflictKey))
                sourceColumns.Add($"NULL AS {conflictKey}");

            // INSERT 子句的值清单引用源表列
            var sourceValueColumns = new List<string>(insertColumns.Count);
            foreach (var column in insertColumns)
            {
                sourceValueColumns.Add($"src.{column}");
            }

            var sqlBuilder = new StringBuilder();

            // 自增列带显式值（进入插入列清单）时，IDENTITY_INSERT 默认关闭的表无法显式插入标识列，
            // 以同命令多语句批处理包裹 SET IDENTITY_INSERT ON/OFF（与 PostgreSQL 的 GENERATED BY DEFAULT、
            // MySQL/SQLite 的可显式插入语义对齐：冲突判定按显式值进行，不冲突时按显式值插入）
            var needsIdentityInsert = identity != null && identity.IsExplicit;
            if (needsIdentityInsert)
                sqlBuilder.AppendLine($"SET IDENTITY_INSERT {tableName} ON;");

            // WITH (HOLDLOCK) 防止并发下的竞态（同时判定不匹配导致重复插入）；语句以分号结尾（MERGE 语法要求）
            sqlBuilder.AppendLine($"MERGE INTO {tableName} WITH (HOLDLOCK) AS t");
            sqlBuilder.AppendLine($"USING (SELECT {string.Join(", ", sourceColumns)}) AS src");
            sqlBuilder.AppendLine($"    ON t.{conflictKey} = src.{conflictKey}");
            sqlBuilder.AppendLine("WHEN MATCHED THEN");
            sqlBuilder.AppendLine($"    UPDATE SET {string.Join(", ", updateAssignments)}");

            sqlBuilder.AppendLine("WHEN NOT MATCHED THEN");
            // MERGE 的 INSERT 子句不带 INTO（区别于普通 INSERT INTO）
            sqlBuilder.AppendLine($"    INSERT ({string.Join(", ", insertColumns)})");
            sqlBuilder.AppendLine($"    VALUES ({string.Join(", ", sourceValueColumns)})");

            // 自增 ID 取回：OUTPUT INSERTED 以结果集方式返回（调用方仅对支持结果集取回的方言构造取回上下文；显式写入形态不取回）
            if (identity != null && !identity.IsExplicit)
                sqlBuilder.AppendLine($"OUTPUT INSERTED.{identity.IdentityColumn};");
            else
                sqlBuilder.AppendLine(";");// MERGE 语句必须以分号结尾

            if (needsIdentityInsert)
                sqlBuilder.AppendLine($"SET IDENTITY_INSERT {tableName} OFF;");

            return sqlBuilder.ToString();
        }

        /// <summary>
        /// 构建窗口查询语句（分页与 Skip/Take 共享的核心）。根据 SQL Server 版本选择不同的语法：
        /// 2012 及以上使用 OFFSET/FETCH，2008 及以下使用 ROW_NUMBER，offset 由入口换算后直传。
        /// </summary>
        /// <param name="querySql">原始查询 SQL 语句（已修剪），不得自带顶层 ORDER BY。</param>
        /// <param name="offset">跳过的行数。</param>
        /// <param name="fetch">取回的行数。</param>
        /// <param name="orderBy">ORDER BY 子句。</param>
        /// <param name="appendRowOrder">是否保证输出行序。</param>
        /// <param name="serverInfo">服务器信息。</param>
        /// <returns></returns>
        protected override string BuildWindowSqlCore(string querySql,
            int offset,
            int fetch,
            string orderBy,
            bool appendRowOrder,
            DbServerInfo serverInfo = null)
        {
            if (IsOffsetAndFetchSupported(serverInfo))
            {
                // 对于 SQL Server 2012 及以上版本，使用 OFFSET 和 FETCH NEXT 实现分页；
                // ORDER BY 是 OFFSET/FETCH 的语法必需成分，行序契约与包裹场景同形（派生表内合法）
                var subqueryAlias = SqlIdentifierHelper.Generate("q");
                var sqlBuilder = new StringBuilder();
                sqlBuilder.AppendLine($"SELECT * FROM (");
                sqlBuilder.AppendLine(SqlFormatter.IndentLines(querySql));
                sqlBuilder.AppendLine($") AS {subqueryAlias}");
                sqlBuilder.AppendLine($"ORDER BY {orderBy}");
                sqlBuilder.AppendLine($"OFFSET {offset} ROWS");
                sqlBuilder.AppendLine($"FETCH NEXT {fetch} ROWS ONLY");
                return sqlBuilder.ToString();
            }
            else
            {
                // 2008 及以下使用 ROW_NUMBER() 方法：嵌套派生表形态，可被聚合/投影再包裹
                long endRow = offset + fetch;// 计算结束行号

                // 别名带随机段防撞：实体列名恰为 q/rn 时固定别名会与派生表列名重复
                string innerAlias = SqlIdentifierHelper.Generate("q");
                string outerAlias = SqlIdentifierHelper.Generate("q");
                string rowNumberAlias = SqlIdentifierHelper.Generate("rn");

                var rowNumberBuilder = new StringBuilder();
                rowNumberBuilder.AppendLine("SELECT * FROM (");
                rowNumberBuilder.AppendLine($"    SELECT {innerAlias}.*, ROW_NUMBER() OVER (ORDER BY {orderBy}) AS {rowNumberAlias}");
                rowNumberBuilder.AppendLine($"    FROM (");
                rowNumberBuilder.AppendLine(SqlFormatter.IndentLines(querySql, 2));
                rowNumberBuilder.AppendLine($"    ) AS {innerAlias}");
                rowNumberBuilder.AppendLine($") {outerAlias}");
                rowNumberBuilder.AppendLine($"WHERE {rowNumberAlias} > {offset} AND {rowNumberAlias} <= {endRow}");

                // 顶层排序契约：行序必须等于排序键序——过滤后的行集若不显式 ORDER BY，行序在 SQL 语义上
                // 不保证（优化器无契约保留 ROW_NUMBER 的计算序），与 OFFSET/FETCH 路径（有顶层 ORDER BY）一致；
                // 包裹场景（appendRowOrder=false）行序由外层保证，省略尾部排序
                if (appendRowOrder)
                    rowNumberBuilder.AppendLine($"ORDER BY {orderBy}");

                return rowNumberBuilder.ToString();
            }
        }

        /// <summary>
        /// 是否支持 OFFSET 和 FETCH 语句。
        /// </summary>
        /// <param name="serverInfo">数据库服务器版本信息。</param>
        /// <returns></returns>
        private static bool IsOffsetAndFetchSupported(DbServerInfo serverInfo)
        {
            // 如果没有版本信息，默认使用兼容语法
            if (serverInfo == null)
                return false;

            // 从 SQL Server 2012 开始支持 OFFSET 和 FETCH NEXT（版本 11.0）
            return serverInfo.MajorVersion >= 11;
        }
    }
}
